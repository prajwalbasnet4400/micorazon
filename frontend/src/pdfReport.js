import { jsPDF } from 'jspdf'
import { FIELDS, SECTIONS, formatValue } from './medicalInfo'

const COLORS = {
  title: [55, 48, 163],
  general: [30, 64, 175],
  medical: [124, 58, 237],
  habit: [219, 39, 119],
  healthy: [22, 163, 74],
  risk: [220, 38, 38],
  text: [17, 24, 39],
  muted: [107, 114, 128],
}

export function generateReport(user, result) {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' })
  const pageWidth = doc.internal.pageSize.getWidth()
  const pageHeight = doc.internal.pageSize.getHeight()
  const left = 56
  const width = pageWidth - left * 2
  let y = 64

  const ensureSpace = (needed) => {
    if (y + needed > pageHeight - 60) {
      doc.addPage()
      y = 64
    }
  }
  const heading = (text, color, size = 13) => {
    ensureSpace(32)
    y += 10
    doc.setFont('helvetica', 'bold').setFontSize(size).setTextColor(...color)
    doc.text(text, left, y)
    doc.setDrawColor(...color).setLineWidth(0.6).line(left, y + 4, left + 160, y + 4)
    y += 20
  }
  const line = (label, value) => {
    ensureSpace(16)
    doc.setFont('helvetica', 'bold').setFontSize(10).setTextColor(...COLORS.text)
    doc.text(`${label}:`, left, y)
    const labelWidth = doc.getTextWidth(`${label}: `) // measure while still bold
    doc.setFont('helvetica', 'normal')
    doc.text(String(value), left + labelWidth, y)
    y += 15
  }
  const paragraph = (text) => {
    doc.setFont('helvetica', 'normal').setFontSize(10).setTextColor(...COLORS.text)
    const lines = doc.splitTextToSize(text, width - 14)
    ensureSpace(lines.length * 13 + 4)
    doc.text('•', left, y)
    doc.text(lines, left + 12, y)
    y += lines.length * 13 + 4
  }

  // Header
  doc.setFont('helvetica', 'bold').setFontSize(20).setTextColor(...COLORS.title)
  doc.text('Heart Failure Risk Assessment Report', pageWidth / 2, y, { align: 'center' })
  y += 18
  doc.setFont('helvetica', 'normal').setFontSize(9).setTextColor(...COLORS.muted)
  doc.text(`Generated on: ${new Date().toLocaleString()}`, pageWidth / 2, y, { align: 'center' })
  y += 18

  // Prediction result
  const atRisk = result.status === 'At Risk'
  heading('Prediction Result', COLORS.title, 14)
  doc.setFont('helvetica', 'bold').setFontSize(12).setTextColor(...(atRisk ? COLORS.risk : COLORS.healthy))
  doc.text(`Status: ${result.status} (${result.risk_level} risk)`, left, y)
  y += 18
  line('Healthy Probability', `${(result.probability_healthy * 100).toFixed(2)}%`)
  line('Risk Probability', `${(result.probability_at_risk * 100).toFixed(2)}%`)

  // Patient information
  heading('Patient Details', COLORS.general)
  line('Name', user.name)
  line('Email', user.email)
  line('Phone', user.phone)
  line('Address', user.address)

  for (const section of SECTIONS) {
    heading(section.title, COLORS[section.key])
    for (const key of section.fields) line(FIELDS[key].label, formatValue(key, result.inputs[key]))
  }

  heading('Key Contributing Factors', COLORS.title)
  for (const f of result.top_factors) {
    paragraph(`${f.label} (${formatValue(f.feature, f.value)}) ${f.direction} the predicted risk.`)
  }

  heading('Suggestions', COLORS.title)
  for (const tip of result.suggestions) paragraph(tip)

  // Footer on every page
  const pages = doc.getNumberOfPages()
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i)
    doc.setFont('helvetica', 'normal').setFontSize(8).setTextColor(...COLORS.muted)
    doc.text(
      'This report is generated by the Heart Failure Risk Prediction System and is not a medical diagnosis.',
      pageWidth / 2,
      pageHeight - 30,
      { align: 'center' },
    )
    doc.text(`Page ${i} of ${pages}`, pageWidth - left, pageHeight - 30, { align: 'right' })
  }

  const safeName = user.name.replace(/[^a-z0-9]+/gi, '_')
  doc.save(`HFP_Report_${safeName}_${result.id}.pdf`)
}
