"""Build the 2000-record training dataset from the UCI heart failure clinical records.

The public UCI dataset (Chicco & Jurman, 2020) has only 299 patients. Following the
project report (2000 records), we expand it with synthetic patients generated by
jittering real records: continuous features receive Gaussian noise (in log space for
skewed lab values), binary features are occasionally flipped, and a small fraction of
labels is flipped to avoid producing an unrealistically separable dataset.

Each row keeps a ``source_id`` pointing at the real patient it was derived from, so
training can split by patient group and never test on near-copies of training rows.

Usage:
    uv run python ml/make_dataset.py [--rows 2000] [--seed 42]
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from features import BINARY_FEATURES, CONTINUOUS_FEATURES, FEATURES, LOG_SCALE_FEATURES, TARGET

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "data" / "heart_failure_clinical_records_uci.csv"
OUTPUT = ROOT / "data" / "heart_failure_clinical_records_2000.csv"

# Clinically plausible bounds and rounding for each continuous feature.
BOUNDS = {
    "age": (40, 95, 0),
    "creatinine_phosphokinase": (23, 7861, 0),
    "ejection_fraction": (14, 80, 0),
    "platelets": (25_100, 850_000, -2),
    "serum_creatinine": (0.5, 9.4, 1),
    "serum_sodium": (113, 148, 0),
    "time": (4, 285, 0),
}

NOISE_SCALE = 0.15  # fraction of a feature's std used as jitter
BINARY_FLIP_P = 0.05
LABEL_FLIP_P = 0.05


def expand(df: pd.DataFrame, rows: int, seed: int) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    df = df.assign(source_id=np.arange(len(df)))
    n_new = rows - len(df)
    if n_new <= 0:
        return df.sample(rows, random_state=seed).reset_index(drop=True)

    base = df.iloc[rng.integers(0, len(df), n_new)].reset_index(drop=True).copy()

    for col in CONTINUOUS_FEATURES:
        low, high, decimals = BOUNDS[col]
        if col in LOG_SCALE_FEATURES:
            logged = np.log(df[col])
            noisy = np.exp(np.log(base[col]) + rng.normal(0, NOISE_SCALE * logged.std(), n_new))
        else:
            noisy = base[col] + rng.normal(0, NOISE_SCALE * df[col].std(), n_new)
        base[col] = np.clip(noisy, low, high).round(decimals)

    for col in BINARY_FEATURES:
        flip = rng.random(n_new) < BINARY_FLIP_P
        base.loc[flip, col] = 1 - base.loc[flip, col]

    flip = rng.random(n_new) < LABEL_FLIP_P
    base.loc[flip, TARGET] = 1 - base.loc[flip, TARGET]

    out = pd.concat([df, base], ignore_index=True)
    out = out.sample(frac=1, random_state=seed).reset_index(drop=True)
    int_cols = [c for c in FEATURES + [TARGET, "source_id"] if c not in ("serum_creatinine", "platelets")]
    out[int_cols] = out[int_cols].astype(int)
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--rows", type=int, default=2000)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    df = pd.read_csv(SOURCE)
    out = expand(df, args.rows, args.seed)
    out.to_csv(OUTPUT, index=False)
    counts = out[TARGET].value_counts().to_dict()
    print(f"Wrote {len(out)} rows to {OUTPUT.relative_to(ROOT)} (class balance: {counts})")


if __name__ == "__main__":
    main()
